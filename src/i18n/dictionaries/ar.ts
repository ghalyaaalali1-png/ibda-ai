const n = (v: number) => v.toLocaleString("en-US");
/** Keeps a run of numbers left-to-right inside Arabic text, so "600–1,000" isn't reversed. */
const ltr = (text: string) => `⁦${text}⁩`;
const ARABIC_START = /^[؀-ۿ]/;

/** "أ، ب وج" — "و" joins an Arabic word, and stands apart before a Latin one. */
function list(items: string[]) {
  if (items.length <= 1) return items.join("");
  const last = items.at(-1)!;
  return `${items.slice(0, -1).join("، ")} ${ARABIC_START.test(last) ? `و${last}` : `و ${last}`}`;
}

